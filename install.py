# Routes
# ===========================================================================

@install_bp.route('/', methods=['GET'])
def index():
    """Redirect /install → /install/step1."""
    return redirect(url_for('install.step1'))


# ---------------------------------------------------------------------------
# Step 1 — PostgreSQL connection settings
# ---------------------------------------------------------------------------

@install_bp.route('/step1', methods=['GET', 'POST'])
def step1():
    """Display and process the database connection form.

    On GET  : Show the form pre-filled with defaults (or previously entered
              values stored in the Flask session).
    On POST : Validate the form, test the PostgreSQL connection, and on success
              persist the values in the session and redirect to Step 2.

    Returns:
        Rendered HTML page or redirect to step2.
    """
    if request.method == 'POST':
        pg_host     = request.form.get('pg_host',     'localhost').strip()
        pg_port     = request.form.get('pg_port',     '5432').strip()
        pg_user     = request.form.get('pg_user',     '').strip()
        pg_password = request.form.get('pg_password', '').strip()
        pg_db       = request.form.get('pg_db',       'bd_userslinker').strip()

        # ----------------------------------------------------------------
        # Quick client-side-style validation (server side)
        # ----------------------------------------------------------------
        if not pg_user:
            flash('Database username is required.', 'danger')
            return render_template('install/step1.html', step=1,
                                   pg_host=pg_host, pg_port=pg_port,
                                   pg_user=pg_user, pg_password=pg_password,
                                   pg_db=pg_db)

        # ----------------------------------------------------------------
        # Test the connection before going further
        # ----------------------------------------------------------------
        try:
            import psycopg2  # type: ignore
            conn = psycopg2.connect(
                host=pg_host,
                port=int(pg_port),
                user=pg_user,
                password=pg_password,
                dbname=pg_db,
                connect_timeout=5,
            )
            conn.close()
        except Exception as exc:
            flash(f'Connection failed: {exc}', 'danger')
            return render_template('install/step1.html', step=1,
                                   pg_host=pg_host, pg_port=pg_port,
                                   pg_user=pg_user, pg_password=pg_password,
                                   pg_db=pg_db)

        # ----------------------------------------------------------------
        # Store settings in the server-side session for the next steps
        # ----------------------------------------------------------------
        session['pg_host']     = pg_host
        session['pg_port']     = pg_port
        session['pg_user']     = pg_user
        session['pg_password'] = pg_password
        session['pg_db']       = pg_db

        flash('Database connection successful!', 'success')
        return redirect(url_for('install.step2'))

    # GET — pre-fill from session (back-navigation) or with safe defaults
    return render_template(
        'install/step1.html',
        step=1,
        pg_host     = session.get('pg_host',     'localhost'),
        pg_port     = session.get('pg_port',     '5432'),
        pg_user     = session.get('pg_user',     'userslinker_app'),
        pg_password = session.get('pg_password', ''),
        pg_db       = session.get('pg_db',       'bd_userslinker'),
    )


# ---------------------------------------------------------------------------
# Step 2 — Create tables
# ---------------------------------------------------------------------------

@install_bp.route('/step2', methods=['GET', 'POST'])
def step2():
    """Create all application tables inside PostgreSQL.

    On GET  : Show a confirmation screen listing what will be created.
    On POST : Use SQLAlchemy + the db_setup model definitions to create every
              table, seed the three default roles, then redirect to Step 3.

    Returns:
        Rendered HTML page or redirect to step3.
    """
    # Guard: step1 must have been completed first
    if 'pg_host' not in session:
        flash('Please complete Step 1 first.', 'warning')
        return redirect(url_for('install.step1'))

    if request.method == 'POST':
        try:
            from db_setup import (
                db as setup_db,
                Role,
                AppManagement,
                Users,
                Computers,
                Monitors,
                Peripherals,
                Phones,
                History,
            )
            from flask_security import SQLAlchemySessionUserDatastore
            from sqlalchemy import create_engine
            from sqlalchemy.orm import sessionmaker

            # Build a temporary engine from the connection settings entered
            # in step1.  No search_path needed — every model already declares
            # __table_args__ = {'schema': 'app'}, so SQLAlchemy always emits
            # fully-qualified names like  app.app_management,  app.role, etc.
            uri = _build_uri(
                session['pg_host'],
                session['pg_port'],
                session['pg_user'],
                session['pg_password'],
                session['pg_db'],
            )
            tmp_engine = create_engine(uri)

            # Create all tables declared in db_setup.py inside the 'app' schema.
            # metadata.create_all() takes an explicit engine, bypassing the
            # engine that Flask-SQLAlchemy bound at startup.
            setup_db.metadata.create_all(tmp_engine)

            # Open a temporary session on the same engine to seed the roles.
            TmpSession = sessionmaker(bind=tmp_engine)
            tmp_session = TmpSession()

            local_datastore = SQLAlchemySessionUserDatastore(
                tmp_session, AppManagement, Role
            )

            if not tmp_session.query(Role).filter_by(name='administrateur').first():
                local_datastore.create_role(
                    name='administrateur',
                    description='Manages application users and their roles',
                )
                local_datastore.create_role(
                    name='gestionnaire',
                    description='Creates events, edits assets and user records',
                )
                local_datastore.create_role(
                    name='lecteur',
                    description='Read-only access to assets and user records',
                )
                tmp_session.commit()

            tmp_session.close()
            tmp_engine.dispose()

            flash('Tables created and roles seeded successfully!', 'success')
            return redirect(url_for('install.step3'))

        except Exception as exc:
            flash(f'Error during table creation: {exc}', 'danger')

    return render_template('install/step2.html', step=2,
                           pg_db=session.get('pg_db', ''))


# ---------------------------------------------------------------------------
# Step 3 — Create the first administrator account
# ---------------------------------------------------------------------------

@install_bp.route('/step3', methods=['GET', 'POST'])
def step3():
    """Create the first (and only required) administrator account.

    On GET  : Show the admin account creation form.
    On POST : Validate inputs, create the account, write the .env file, write
              the installed.lock sentinel, then redirect to the finish page.

    Returns:
        Rendered HTML page or redirect to finish.
    """
    if 'pg_host' not in session:
        flash('Please complete Step 1 first.', 'warning')
        return redirect(url_for('install.step1'))

    if request.method == 'POST':
        given_name = request.form.get('given_name', '').strip()
        surname    = request.form.get('surname',    '').strip()
        username   = request.form.get('username',   '').strip()
        email      = request.form.get('email',      '').strip()
        password   = request.form.get('password',   '').strip()
        password2  = request.form.get('password2',  '').strip()

        # ----------------------------------------------------------------
        # Validation
        # ----------------------------------------------------------------
        errors = []
        if not email:
            errors.append('Email address is required.')
        if not password:
            errors.append('Password is required.')
        if password != password2:
            errors.append('Passwords do not match.')
        if len(password) < 8:
            errors.append('Password must be at least 8 characters.')

        if errors:
            for err in errors:
                flash(err, 'danger')
            return render_template('install/step3.html', step=3,
                                   given_name=given_name, surname=surname,
                                   username=username, email=email)

        try:
            from db_setup import (
                db as setup_db,
                Role,
                AppManagement,
            )
            from flask_security import SQLAlchemySessionUserDatastore, hash_password
            from sqlalchemy import create_engine
            from sqlalchemy.orm import sessionmaker

            # ----------------------------------------------------------------
            # STEP A — Générer les clés définitives et les écrire dans .env
            # ----------------------------------------------------------------
            final_secret_key = secrets.token_hex(32)
            final_password_salt = secrets.token_hex(16)

            _write_env(
                host=session['pg_host'],
                port=session['pg_port'],
                user=session['pg_user'],
                password=session['pg_password'],
                db=session['pg_db'],
                secret_key=final_secret_key,
                password_salt=final_password_salt,
            )

            # ----------------------------------------------------------------
            # STEP B — Pousser les clés définitives dans current_app.config
            # AVANT d'appeler hash_password().
            # hash_password() lit SECURITY_PASSWORD_SALT depuis le config —
            # si on ne met pas à jour le config maintenant, il utiliserait
            # encore l'ancien salt et le hash serait incompatible avec les
            # clés que Flask chargera depuis le .env au prochain démarrage.
            # ----------------------------------------------------------------
            current_app.config['SECRET_KEY'] = final_secret_key
            current_app.config['SECURITY_PASSWORD_SALT'] = final_password_salt

            # Hasher le mot de passe avec les clés définitives maintenant
            # en place dans le config — ce hash sera valide après redémarrage.
            hashed_pw = hash_password(password)

            # ----------------------------------------------------------------
            # STEP C — Persister le compte admin
            # ----------------------------------------------------------------
            uri = _build_uri(
                session['pg_host'],
                session['pg_port'],
                session['pg_user'],
                session['pg_password'],
                session['pg_db'],
            )
            tmp_engine = create_engine(uri)
            TmpSession = sessionmaker(bind=tmp_engine)
            tmp_session = TmpSession()

            # Rejeter les emails en doublon
            if tmp_session.query(AppManagement).filter_by(email=email).first():
                tmp_session.close()
                tmp_engine.dispose()
                flash('An account with this email already exists.', 'danger')
                return render_template(
                    'install/step3.html', step=3,
                    given_name=given_name, surname=surname,
                    username=username, email=email,
                )

            local_datastore = SQLAlchemySessionUserDatastore(
                tmp_session, AppManagement, Role
            )

            # Passer le hash pré-calculé — create_user() le stocke tel quel
            # sans re-hasher (confirmé dans le code source de Flask-Security).
            admin_user = local_datastore.create_user(
                email=email,
                password=hashed_pw,
                GivenName=given_name,
                Surname=surname,
                user=username or email.split('@')[0],
            )
            admin_role = tmp_session.query(Role).filter_by(name='administrateur').first()
            local_datastore.add_role_to_user(admin_user, admin_role)
            tmp_session.commit()
            tmp_session.close()
            tmp_engine.dispose()

            # ----------------------------------------------------------------
            # STEP D — Écrire le sentinel — /install inaccessible après restart
            # ----------------------------------------------------------------
            _write_lock()

            # Vider les données du wizard de la session
            for key in ('pg_host', 'pg_port', 'pg_user', 'pg_password', 'pg_db'):
                session.pop(key, None)

            return redirect(url_for('install.finish'))

        except Exception as exc:
            flash(f'Error creating admin account: {exc}', 'danger')

    return render_template('install/step3.html', step=3,
                           given_name='', surname='', username='', email='')


# ---------------------------------------------------------------------------
# Finish page
# ---------------------------------------------------------------------------

@install_bp.route('/finish')
def finish():
    """Display the installation success screen.

    Informs the administrator that:
    - The .env file has been written.
    - installed.lock has been created.
    - They should restart the Flask server.
    - /install will no longer be accessible after the restart.

    Returns:
        Rendered HTML success page.
    """
    return render_template('install/finish.html', step=4)