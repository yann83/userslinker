# install.py
"""
Web-based installation wizard for the UsersLinker Flask application.

Inspired by GLPI's install.php, this blueprint exposes a /install route that
guides the administrator through:
    Step 1 – Enter PostgreSQL connection settings and write the .env file.
    Step 2 – Test the database connection and create all application tables.
    Step 3 – Create the first administrator account.

Once the wizard completes successfully it writes an "installed.lock" sentinel
file to the project root.  app.py checks for that file on startup:
  • If the file does NOT exist  → the blueprint is registered and /install works.
  • If the file DOES exist      → the blueprint is never registered and /install
                                  returns 404, just like deleting install.php.

Location: install.py  (root of the project, same folder as app.py)
"""

import os
import secrets
from datetime import datetime, timezone

from flask import (
    Blueprint,
    render_template,
    request,
    redirect,
    url_for,
    flash,
    session,
    current_app,
)
from flask_sqlalchemy import SQLAlchemy
from flask_security import (
    Security,
    SQLAlchemySessionUserDatastore,
    UserMixin,
    RoleMixin,
    hash_password,
)

# ---------------------------------------------------------------------------
# Blueprint declaration
# ---------------------------------------------------------------------------
install_bp = Blueprint(
    'install',
    __name__,
    url_prefix='/install',
    template_folder='templates',   # reuses the main templates/ folder
)

# Path to the sentinel file that marks a completed installation.
# Once this file exists the blueprint is no longer registered.
LOCK_FILE = os.path.join(os.path.dirname(__file__), 'installed.lock')
ENV_FILE  = os.path.join(os.path.dirname(__file__), '.env')


# ===========================================================================
# Helper utilities
# ===========================================================================

def _build_uri(host: str, port: str, user: str, password: str, db: str) -> str:
    """Build a SQLAlchemy PostgreSQL URI from individual connection parameters.

    Args:
        host:     PostgreSQL server hostname or IP address.
        port:     TCP port (default 5432).
        user:     Database role / username.
        password: Password for that role.
        db:       Name of the database to connect to.

    Returns:
        A fully-formed ``postgresql+psycopg2://…`` URI string.
    """
    return f'postgresql+psycopg2://{user}:{password}@{host}:{port}/{db}'


def _write_env(host: str, port: str, user: str, password: str, db: str,
               secret_key: str, password_salt: str) -> None:
    """Write (or overwrite) the .env file with the supplied settings.

    Args:
        host:          PostgreSQL server hostname.
        port:          PostgreSQL server port.
        user:          Database username.
        password:      Database password.
        db:            Database name.
        secret_key:    Flask SECRET_KEY value.
        password_salt: Flask-Security SECURITY_PASSWORD_SALT value.
    """
    content = f"""# .env  –  generated by the UsersLinker installation wizard on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}
#
# IMPORTANT:
#   - Never commit this file to a public repository (add it to .gitignore).
#   - Change SECRET_KEY and SECURITY_PASSWORD_SALT before going to production.
#
# Location: .env  (root of the project, same folder as app.py)

# -----------------------------------------------------------------------------
# PostgreSQL connection settings
# -----------------------------------------------------------------------------
PG_HOST={host}
PG_USER={user}
PG_PASSWORD={password}
PG_DB={db}
PG_PORT={port}

# -----------------------------------------------------------------------------
# Security keys  (auto-generated — keep these secret)
# -----------------------------------------------------------------------------
SECRET_KEY={secret_key}
SECURITY_PASSWORD_SALT={password_salt}

# -----------------------------------------------------------------------------
# Flask runtime settings
# Set FLASK_DEBUG=0 in production.
# -----------------------------------------------------------------------------
FLASK_DEBUG=0
"""
    with open(ENV_FILE, 'w', encoding='utf-8') as fh:
        fh.write(content)


def _write_lock() -> None:
    """Create the installed.lock sentinel file.

    This file signals to app.py that the installation is complete.
    app.py will NOT register the install blueprint when this file exists,
    effectively making /install unreachable (same idea as deleting install.php).
    """
    with open(LOCK_FILE, 'w', encoding='utf-8') as fh:
        fh.write(
            f'UsersLinker installed on {datetime.now(timezone.utc).isoformat()}\n'
            'Delete this file only if you need to re-run the installation wizard.\n'
        )


